"""Build MimicCam for Windows.

    python build.py                # portable folder + zip
    python build.py --installer    # also run Inno Setup if it is installed

Signing (optional, see SIGNING.md). Set one identity before building and every
binary carries "Ray Bekson (bigrayszn)" as its verified publisher:

    set MIMICCAM_SIGN_PFX=C:\certs\mimiccam.pfx
    set MIMICCAM_SIGN_PASSWORD=...            (or use a store thumbprint)
    set MIMICCAM_SIGN_THUMBPRINT=...          (cert already in your store)

Output:
    dist/MimicCam/MimicCam.exe
    dist/MimicCam-<version>-win64-portable.zip
    dist/MimicCam-<version>-setup.exe      (with --installer)
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DIST = ROOT / "dist"
BUILD = ROOT / "build"
ICON = ROOT / "assets" / "mimiccam.ico"

# Who published the binary. These land in the exe's version resource, which is
# what Explorer shows under Properties -> Details and what a signing certificate
# is checked against.
AUTHOR = "Ray Bekson (bigrayszn)"
HOMEPAGE = "https://github.com/bigrayszn/mimiccam"
COPYRIGHT_LINE = "Copyright (C) 2026 Ray Bekson (bigrayszn) - GPL-2.0-or-later"
TIMESTAMP_URL = "http://timestamp.digicert.com"

# Windows refuses to load a DLL when the full path nears MAX_PATH. The deepest
# bundled name is pyvirtualcam's native module, roughly this long.
NATIVE_NAME_LEN = len("_internal\\pyvirtualcam\\_native_windows_unity_capture.cp310-win_amd64.pyd")
PATH_BUDGET = 240

sys.path.insert(0, str(ROOT))
from mimiccam import __version__  # noqa: E402


def run(cmd: list[str]) -> None:
    print("\n$", " ".join(cmd))
    subprocess.run(cmd, check=True, cwd=str(ROOT))


def ensure_pyinstaller() -> None:
    if importlib.util.find_spec("PyInstaller") is None:
        run([sys.executable, "-m", "pip", "install", "pyinstaller>=6.6"])


def version_tuple() -> tuple[int, int, int, int]:
    parts = [int(p) for p in __version__.split(".") if p.isdigit()]
    parts += [0] * (4 - len(parts))
    return tuple(parts[:4])  # type: ignore[return-value]


def write_version_file() -> Path:
    """PyInstaller's version resource: company, copyright and product strings.

    Without this the exe's Properties page says nothing about who wrote it, and a
    signed build would have a publisher name but no owner recorded inside the
    binary itself.
    """
    BUILD.mkdir(parents=True, exist_ok=True)
    out = BUILD / "version_info.txt"
    v = version_tuple()
    dotted = ".".join(str(n) for n in v)
    strings = [
        ("CompanyName", AUTHOR),
        ("FileDescription", f"MimicCam {__version__} - real-time character swap webcam"),
        ("FileVersion", dotted),
        ("InternalName", "MimicCam"),
        ("LegalCopyright", COPYRIGHT_LINE),
        ("OriginalFilename", "MimicCam.exe"),
        ("ProductName", "MimicCam"),
        ("ProductVersion", __version__),
        ("Comments", HOMEPAGE),
    ]
    table = ",\n".join(
        f"            StringStruct({name!r}, {value!r})" for name, value in strings
    )
    out.write_text(
        "# Generated by build.py - do not edit.\n"
        "VSVersionInfo(\n"
        f"  ffi=FixedFileInfo(filevers={v}, prodvers={v}, mask=0x3f, flags=0x0,\n"
        "                  OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),\n"
        "  kids=[\n"
        "    StringFileInfo([\n"
        "        StringTable('040904B0', [\n"
        f"{table}\n"
        "        ])\n"
        "    ]),\n"
        "    VarFileInfo([VarStruct('Translation', [1033, 1200])])\n"
        "  ]\n"
        ")\n",
        encoding="utf-8",
    )
    return out


def pyinstaller_args() -> list[str]:
    args = [
        sys.executable, "-m", "PyInstaller",
        "--noconfirm", "--clean",
        "--windowed",
        "--name", "MimicCam",
        "--onedir",
        "--distpath", str(DIST),
        "--workpath", str(BUILD),
        "--specpath", str(BUILD),
        # The RTC/Decart stack loads native modules and plugins dynamically.
        "--collect-all", "livekit",
        "--collect-all", "decart",
        "--collect-all", "av",
        "--hidden-import", "keyring.backends.Windows",
        "--hidden-import", "pyvirtualcam",
        # Offline engine: onnxruntime is imported lazily and ships DirectML.dll
        # next to its own package, so both have to be collected explicitly.
        "--collect-all", "onnxruntime",
        "--hidden-import", "onnx",
        # Keep the bundle sane: we never use these Qt modules.
        "--exclude-module", "PySide6.QtWebEngineCore",
        "--exclude-module", "PySide6.QtWebEngineWidgets",
        "--exclude-module", "PySide6.QtQuick3D",
        "--exclude-module", "PySide6.Qt3DCore",
        "--exclude-module", "tkinter",
        "--exclude-module", "matplotlib",
        "--exclude-module", "pytest",
    ]
    if ICON.exists():
        args += ["--icon", str(ICON)]
    args += ["--version-file", str(write_version_file())]
    args.append(str(ROOT / "main.py"))
    return args


def net(path: Path) -> str:
    """Backslash form Windows actually sees, for length checks and logs."""
    return str(path).replace("/", "\\")


def path_budget_note(exe: Path) -> None:
    deepest = len(net(exe)) + NATIVE_NAME_LEN
    if deepest + 12 > PATH_BUDGET:
        print(
            "\nWARNING: this build lives at\n  "
            f"{net(exe)}\n"
            f"The deepest bundled file is {deepest} characters, close to (or past) Windows' "
            f"{PATH_BUDGET}-character practical limit. Users who unzip this here will not be "
            "able to load the virtual-camera driver. Build into a short path instead:\n"
            "  python build.py --dist C:\\MimicCam-dist"
        )
    else:
        print(f"\nPath budget: deepest bundled file is {deepest} characters (limit {PATH_BUDGET}).")


# Printed by --list-backends when pyvirtualcam loaded fine but no DirectShow
# virtual camera is registered on the machine. A CI runner looks exactly like
# that: the driver is present in the bundle, there is just nothing to write to.
NO_VCAM_LINE = "Available virtual-camera backends: none"


def smoke_test(exe: Path) -> None:
    """Run the frozen binary before publishing it.

    A build can succeed and still produce an exe that cannot import its own native
    dependencies; this catches that here rather than in a user's call.
    """
    print(f"\nSmoke test: {exe.name} --list-backends")
    attempts = 3
    for attempt in range(1, attempts + 1):
        try:
            proc = subprocess.run(
                [str(exe), "--list-backends"], capture_output=True, text=True, timeout=180
            )
        except subprocess.TimeoutExpired:
            raise SystemExit(
                "SMOKE TEST FAILED: the frozen exe did not exit. This usually means an "
                "error dialog is waiting behind the scenes - run it by hand to see it."
            )
        output = (proc.stdout or "") + (proc.stderr or "")
        # "none" means the driver imported and simply found no registered
        # filter, so retrying cannot help. That line is only reachable when the
        # import succeeded, which is what this test is actually about.
        if proc.returncode == 0 or NO_VCAM_LINE in output or attempt == attempts:
            break
        # The OBS virtual camera reports "no backend" for a second or two while its
        # filter is starting, which is a machine state, not a broken build. A build
        # that really cannot load its stack fails all three attempts.
        print(f"  attempt {attempt}: no backend yet, retrying in 3s")
        time.sleep(3)
    print("  exit:", proc.returncode)
    for line in output.strip().splitlines()[-6:]:
        print("  exe|", line)
    if proc.returncode != 0 and NO_VCAM_LINE in output:
        print(
            "  SKIP - the virtual-camera driver loaded but this machine has no "
            "DirectShow camera registered.\n"
            "         Expected on a CI runner; install OBS Studio locally to test the "
            "write path."
        )
    elif proc.returncode != 0:
        hint = ""
        if "too long" in output.lower():
            hint = (
                "\n  Cause: the build path is too deep for Windows to load a DLL. "
                "Rebuild with --dist C:\\MimicCam-dist"
            )
        raise SystemExit(f"SMOKE TEST FAILED: the frozen exe exited with {proc.returncode}{hint}")
    else:
        print("  PASS - the frozen exe imports its stack and finds a virtual camera")

    print(f"\nSmoke test: {exe.name} --check-local")
    proc = subprocess.run(
        [str(exe), "--check-local"], capture_output=True, text=True, timeout=300
    )
    output = (proc.stdout or "") + (proc.stderr or "")
    print("  exit:", proc.returncode)
    for line in output.strip().splitlines()[-6:]:
        print("  exe|", line)
    if proc.returncode != 0:
        raise SystemExit(
            "SMOKE TEST FAILED: the frozen exe could not run the offline engine. "
            "Check that onnxruntime and DirectML.dll were bundled."
        )
    if "models not installed" in output:
        # --check-local exits 0 when the models simply are not downloaded yet.
        # Saying PASS there would claim a swap that never happened.
        print("  SKIP - no models on this machine, so no swap was run")
        return
    print("  PASS - the frozen exe loads the local models and swaps a frame")


def find_signtool() -> Path | None:
    kits = Path(r"C:\Program Files (x86)\Windows Kits\10\bin")
    if kits.is_dir():
        # 10.0.26100.0 sorts above 10.0.17134.0, so the newest SDK wins.
        found = sorted(kits.glob(r"*\x64\signtool.exe"), reverse=True)
        if found:
            return found[0]
    which = shutil.which("signtool")
    return Path(which) if which else None


def signing_config() -> dict[str, str] | None:
    """The signing identity, from the environment, or None for an unsigned build."""
    # A whole command wins: that is the escape hatch for cloud signers, whose
    # signtool invocation carries a /dlib plugin and metadata that no pfx
    # syntax can express. {file} is replaced with the binary to sign.
    command = os.environ.get("MIMICCAM_SIGN_COMMAND", "").strip()
    if command:
        return {"command": command}
    pfx = os.environ.get("MIMICCAM_SIGN_PFX", "").strip()
    password = os.environ.get("MIMICCAM_SIGN_PASSWORD", "")
    thumbprint = os.environ.get("MIMICCAM_SIGN_THUMBPRINT", "").strip()
    if not pfx and not thumbprint:
        return None
    if pfx and not Path(pfx).exists():
        raise SystemExit(
            f"MIMICCAM_SIGN_PFX points at {pfx}, which does not exist.\n"
            "Unset it to build unsigned, or fix the path."
        )
    return {"pfx": pfx, "password": password, "thumbprint": thumbprint}


def signtool() -> Path:
    tool = find_signtool()
    if tool is None:
        raise SystemExit(
            "A signing identity is configured but signtool.exe was not found.\n"
            "Install the Windows SDK (the Signing Tools component) or put signtool "
            "on PATH. See SIGNING.md."
        )
    return tool


def sign_command(cfg: dict[str, str], path: Path) -> list[str]:
    # /tr timestamps the signature, so it stays valid after the certificate
    # expires instead of every existing install warning about an old signature.
    args = [str(signtool()), "sign", "/fd", "sha256", "/td", "sha256",
            "/tr", TIMESTAMP_URL, "/d", "MimicCam"]
    if cfg["pfx"]:
        args += ["/f", cfg["pfx"]]
        if cfg["password"]:
            args += ["/p", cfg["password"]]
    else:
        args += ["/sha1", cfg["thumbprint"]]
    args.append(str(path))
    return args


# signtool errors that mean "there is a signature, this machine just does not
# trust the chain" - a self-signed or internal-CA certificate. The binary is
# signed; Windows on a machine that trusts the root will show the publisher.
UNTRUSTED_CHAIN = (
    "0x800B0109",
    "0x800B010A",
    "CERT_E_UNTRUSTEDROOT",
    "CERT_E_CHAINING",
    "not trusted by the trust provider",
    "terminated in a root",
)


def verify_signature(path: Path) -> bool:
    """True when the signature is present and nothing about it is broken."""
    tool = find_signtool()
    if tool is None:
        print("  signed - no signtool on PATH to re-verify it")
        return True
    proc = subprocess.run(
        [str(tool), "verify", "/pa", "/v", str(path)], capture_output=True, text=True
    )
    output = (proc.stdout or "") + (proc.stderr or "")
    if proc.returncode == 0:
        print("  PASS - the file carries a signature that verifies")
        return True
    if any(code in output for code in UNTRUSTED_CHAIN):
        print(
            "  signed - the signature is there, but its chain is not trusted on this "
            "machine\n          (self-signed or internal CA). Install the root "
            "certificate to have Windows\n          show the publisher name."
        )
        return True
    print("  verify| " + "\n  verify| ".join(output.strip().splitlines()[-8:]))
    raise SystemExit(f"SIGNING FAILED: the signature on {path.name} does not verify")


def sign(path: Path) -> bool:
    """Sign one binary and prove the signature verifies. Returns True if signed."""
    cfg = signing_config()
    if cfg is None:
        print(
            f"\nSigning: skipped - {path.name} stays unsigned, so Windows shows "
            "\"Unknown publisher\".\n"
            "         Set MIMICCAM_SIGN_PFX + MIMICCAM_SIGN_PASSWORD (or "
            "MIMICCAM_SIGN_THUMBPRINT) to sign; see SIGNING.md."
        )
        return False
    print(f"\nSigning: {path.name}")
    if "command" in cfg:
        cmd = [token.replace("{file}", str(path)) for token in shlex.split(cfg["command"])]
        subprocess.run(cmd, check=True)
    else:
        subprocess.run(sign_command(cfg, path), check=True)
    return verify_signature(path)


# The licence, the copyright statement and the name policy have to travel with the
# download. The installer ships them; this puts the same files beside the exe so the
# portable zip does too.
def copy_paperwork(folder: Path) -> None:
    for name in ("LICENSE", "NOTICE", "COPYRIGHT.md", "TRADEMARK.md", "THIRD_PARTY_NOTICES.md"):
        source = ROOT / name
        if source.exists():
            shutil.copy2(source, folder / name)
    print(f"Paperwork: LICENSE, NOTICE, COPYRIGHT.md, TRADEMARK.md and THIRD_PARTY_NOTICES.md copied beside the exe")


def build_portable() -> Path:
    ensure_pyinstaller()
    if (DIST / "MimicCam").exists():
        shutil.rmtree(DIST / "MimicCam")
    run(pyinstaller_args())

    exe = DIST / "MimicCam" / "MimicCam.exe"
    if not exe.exists():
        raise SystemExit(f"Build finished without producing {exe}")

    path_budget_note(exe)
    if not sign(exe):
        print("  (the portable zip below contains an unsigned exe)")
    smoke_test(exe)
    copy_paperwork(exe.parent)

    archive = DIST / f"MimicCam-{__version__}-win64-portable"
    if Path(f"{archive}.zip").exists():
        Path(f"{archive}.zip").unlink()
    shutil.make_archive(str(archive), "zip", str(DIST), "MimicCam")
    size_mb = Path(f"{archive}.zip").stat().st_size / (1024 * 1024)
    print(f"\nPortable build: {archive}.zip ({size_mb:.0f} MB)")
    return archive


def find_iscc() -> Path | None:
    for candidate in (
        Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
        Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
    ):
        if candidate.exists():
            return candidate
    return shutil.which("iscc") and Path(shutil.which("iscc"))


def build_installer() -> None:
    iscc = find_iscc()
    if not iscc:
        print("Inno Setup not found - skipping installer. Install it from https://jrsoftware.org/isdl.php")
        return
    run([str(iscc), str(ROOT / "installer.iss")])
    print("Installer written to dist/")
    # Inno's own SignTool directive cannot be driven from the command line on
    # this compiler (a define value cannot contain spaces, which every signtool
    # path does), so the setup is signed here instead - which is the file a user
    # downloads and SmartScreen judges. The uninstaller inside it stays unsigned.
    setup = DIST / f"MimicCam-{__version__}-setup.exe"
    if setup.exists():
        if not sign(setup):
            print("  (unsigned - set a signing identity to make Windows show the publisher)")
    else:
        print(f"  (no {setup.name} to sign - installer.iss writes into dist/)")


def main() -> int:
    global DIST
    parser = argparse.ArgumentParser()
    parser.add_argument("--installer", action="store_true", help="also build the Inno Setup installer")
    parser.add_argument("--skip-portable", action="store_true", help="only build the installer")
    parser.add_argument(
        "--dist",
        default=str(DIST),
        help="output folder; use a short path such as C:\\MimicCam-dist when the "
        "repository lives deep inside your user folder",
    )
    args = parser.parse_args()
    DIST = Path(args.dist).expanduser().resolve()
    DIST.mkdir(parents=True, exist_ok=True)

    if not args.skip_portable:
        build_portable()
    if args.installer:
        build_installer()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
